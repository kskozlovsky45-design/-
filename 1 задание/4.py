while True:
    UInput = input("Введите число: → ")

    # Команда выхода
    if UInput == "exit":
        print("Выход из программы...")
        break

    # Убираем возможный минус в начале и проверяем, остались ли только цифры
    # lstrip("-") удаляет все минусы слева, например "-20" -> "20", "20" -> "20"
    if UInput.lstrip("-").isdigit():
        # Подсчитываем количество цифр: убираем минус и берём длину строки
        digits_part = UInput.lstrip("-")  # часть без минуса
        length = len(digits_part)              # количество символов = количество цифр
        print(f"В этом числе {length} цифр.")
    else:
        print("Ошибка: данные не являются числом.")